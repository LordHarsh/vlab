/** The last code the table covers. */
const LAST_CODE = FIRST_CODE + GLYPHS.length / LCD_GLYPH_COLS - 1

/**
 * The 5x8 solid block at CGROM 0xFF.
 *
 * Not decoration: this is the character a module shows in every cell of its
 * first row when it is powered and its contrast is wound past the point where
 * the un-driven segments become visible, and it is what a student sees before
 * their sketch has initialised anything.
 */
const BLOCK: readonly number[] = [0xff, 0xff, 0xff, 0xff, 0xff]

/**
 * The empty box drawn for a code this table does not carry.
 *
 * Deliberately not blank. See the header: a blank cell is a claim about the
 * sketch, a box is a claim about the simulator, and only the second one is true.
 */
const MISSING: readonly number[] = [0x7f, 0x41, 0x41, 0x41, 0x7f]

/**
 * The five column bytes for one CGROM code.
 *
 * Never throws and never returns undefined — a display full of a character set
 * we do not draw must still render as a display.
 */
export function lcdGlyph(code: number): readonly number[] {
  const c = code & 0xff
  if (c === 0xff) return BLOCK
  if (c < FIRST_CODE || c > LAST_CODE) return MISSING
  const at = (c - FIRST_CODE) * LCD_GLYPH_COLS
  return GLYPHS.slice(at, at + LCD_GLYPH_COLS)
}

/** True when this code is one the CGROM table above actually draws. */
export function lcdGlyphKnown(code: number): boolean {
  const c = code & 0xff
  return c === 0xff || (c >= FIRST_CODE && c <= LAST_CODE)
}

/**
 * One CGROM code as the character a HUMAN reads, for the state panel and for
 * tests.
 *
 * This is the A00 mapping and not a cast: 0x5C is a yen sign on the glass, so it
 * is a yen sign here. A code with no glyph becomes U+25AF (a white vertical
 * rectangle), which is the same "cannot draw this" the renderer paints.
 */
export function lcdChar(code: number): string {
  const c = code & 0xff
  if (c === 0x5c) return '¥' // ¥
  if (c === 0x7e) return '→' // →
  if (c === 0x7f) return '←' // ←
  if (c >= 0x20 && c <= 0x7d) return String.fromCharCode(c)
  if (c === 0xff) return '█' // █
  return '▯' // ▯
}

/**
 * A row of CGROM codes as hex, two characters each, no separator.
 *
 * The engine's snapshot carries `Record<string, number | string | boolean>`, so
 * a row of 16 byte codes has to travel as one primitive. Hex rather than a
 * decoded string because the RENDERER needs the codes: it draws dots from the
 * CGROM table, and a string would have already thrown away the distinction
 * between a code we can draw and one we cannot.
 */
export function packLcdRow(codes: ArrayLike<number>): string {
  let out = ''
  for (let i = 0; i < codes.length; i++) out += (codes[i] & 0xff).toString(16).padStart(2, '0')
  return out
}

/** Inverse of packLcdRow(). A malformed or absent string yields no codes. */
export function unpackLcdRow(hex: string): number[] {
  const out: number[] = []
  if (typeof hex !== 'string') return out
  for (let i = 0; i + 1 < hex.length; i += 2) {
    const v = parseInt(hex.slice(i, i + 2), 16)
    out.push(Number.isFinite(v) ? v : 0x20)
  }
  return out
}

/** A packed row as readable text. Used by the state panel and by tests. */
export function lcdRowText(hex: string): string {
  return unpackLcdRow(hex).map(lcdChar).join('')
}
