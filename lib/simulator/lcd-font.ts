/**
 * The HD44780 character generator, as much of it as is honest to draw.
 *
 * A character LCD is the one part in this library whose whole point is what it
 * LOOKS like, so the glyphs cannot be a detail left to a font stack: the module
 * paints a 5x8 dot matrix per cell and a student counting dots is looking at the
 * real thing. Every glyph below is therefore stored the way the controller's own
 * CGROM stores it — five columns of eight dots — and the renderer paints exactly
 * those dots.
 *
 * ─── WHAT IS HERE AND WHAT IS NOT ─────────────────────────────────────────────
 *
 * The A00 ROM (the Japanese one, which is what almost every 1602 module sold to
 * a student carries) holds 240 characters: ASCII in 0x20-0x7F with two
 * substitutions, katakana in 0xA1-0xDF, and a scattering of Greek and maths
 * symbols in 0xE0-0xFF. What is drawn here is the ASCII range, 0x20-0x7F, plus
 * 0xFF — and the three A00 codes inside that range that are NOT their ASCII
 * equivalents are drawn as the A00 ROM draws them, because a sketch that prints
 * a backslash really does get a yen sign on real hardware:
 *
 *   0x5C  ¥  yen, where ASCII has a backslash
 *   0x7E  →  right arrow, where ASCII has a tilde
 *   0x7F  ←  left arrow, where ASCII has DEL
 *   0xFF  █  a solid 5x8 block (the last CGROM entry, and the one a student
 *            sees when a display is powered with its contrast wound to maximum)
 *
 * Anything else — katakana, the Greek block, and the eight CGRAM slots at
 * 0x00-0x07 — is drawn as an EMPTY BOX rather than guessed at or silently
 * blanked. A box says "there is a character here that this simulator cannot
 * draw", which is true; a blank would say "your sketch wrote nothing", which is
 * not. compile.ts states the same thing in words.
 *
 * ─── STORAGE ORDER ────────────────────────────────────────────────────────────
 *
 * Five bytes per glyph, one per COLUMN, left to right. Within a byte, bit 0 is
 * the TOP dot row and bit 7 the bottom — so a 5x7 glyph uses bits 0-6 and leaves
 * bit 7 clear for the cursor line, which is exactly the 5x8 cell the controller
 * addresses. This is the same layout every small graphics library on earth uses
 * for a 5x7 font, which is what makes the table below checkable by eye against
 * any of them.
 */

/** Columns per character cell. */
export const LCD_GLYPH_COLS = 5
/** Dot rows per character cell. Row 7 is the cursor line. */
export const LCD_GLYPH_ROWS = 8

/** The lowest code with a glyph in the table below. */
const FIRST_CODE = 0x20

